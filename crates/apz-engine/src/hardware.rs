/// A built model: its scene root, its parts by id, and the state that `update` drives.
pub struct Built {
    pub root: Obj,
    /// Every built part with an id (a repeated part maps to its group of copies, or to its
    /// instanced mesh).
    pub parts: HashMap<String, Obj>,
    /// The cutaways: each one's box in the model's frame (the board's frame is the world's).
    pub fades: Vec<scene::Fade>,
    /// The cutaway nodes (dynamic while they can fade; see `freeze_cutaways`).
    fade_nodes: Vec<Obj>,
    live: Vec<Live>,
    t: f32,
}

struct Builder {
    vals: BTreeMap<String, f64>,
    parts: HashMap<String, Obj>,
    live: Vec<Live>,
    depth: u32,
    /// The shared materials of plain parts, by their spec (see `material_for`).
    mats: HashMap<String, Mat>,
    /// The cutaway nodes built so far, by id.
    fades: Vec<(u32, Obj)>,
    /// The detail level and cutaway id a part inherits from its ancestors (0: none).
    lod: u8,
    fade: u32,
    /// Whether the parts being built sit under an animated part (a tag, an animation or a cutaway).
    dynamic: bool,
}

impl Builder {
    fn add_parts(&mut self, parent: &Obj, list: &[Part]) {
        // Parts with one key (see `merge_key`) become one instanced draw, placed where the run starts.
        let mut done = vec![false; list.len()];
        for (i, p) in list.iter().enumerate() {
            if done[i] {
                continue;
            }
            done[i] = true;
            if let Some(expr) = &p.when {
                // Validated models only: an unparsable `when` hides the part.
                let shown = parse_when(expr).map(|w| eval_when(&w, &self.vals)).unwrap_or(false);
                if !shown {
                    continue;
                }
            }
            if let Some(key) = self.merge_key(p) {
                let mut run = vec![p];
                for (j, q) in list.iter().enumerate().skip(i + 1) {
                    if !done[j] && self.merge_key(q).as_deref() == Some(key.as_str()) {
                        done[j] = true;
                        run.push(q);
                    }
                }
                if run.len() > 1 {
                    let node = self.merged(&run);
                    parent.add(&node);
                    continue;
                }
            }
            let node = self.part(p);
            parent.add(&node);
        }
    }

    /// The key of a part that can join an instanced run: a plain part (one geometry; no children, part
    /// file, label, animation, cutaway or `when`) that moves, either under an animated part or lit by a
    /// state tag. A state tag (status, activity, screen) drives every copy alike, so a run shares one
    /// material. A fan's spin is per part, so a fan never joins.
    fn merge_key(&self, p: &Part) -> Option<String> {
        let plain = p.geo.is_some()
            && p.repeat.is_none()
            && p.children.is_empty()
            && p.use_.is_none()
            && p.label.is_none()
            && p.anim.is_none()
            && !p.cutaway
            && p.when.is_none();
        let state = matches!(p.tag.as_deref(), None | Some("status" | "activity" | "screen"));
        let moves = self.dynamic || p.tag.is_some();
        (plain && state && moves).then(|| format!("{:?}|{:?}|{:?}|{:?}|{:?}", p.geo, p.mat, p.tag, p.detail, p.outline))
    }

    /// One instanced draw for a run of parts with one key (see `merge_key`): each part's rest pose is its
    /// instance. A state-tagged run is one live node, so its colour or blink drives all its copies.
    fn merged(&mut self, run: &[&Part]) -> Obj {
        let first = run[0];
        let Some(g) = &first.geo else { return Obj::group() };
        let geo = geometry_of(g);
        let mat = self.material_for(first);
        let instances: Vec<Instance> = run
            .iter()
            .map(|p| {
                let at = Vec3::from(p.at.unwrap_or([0.0; 3]));
                let rot = p.rot.unwrap_or([0.0; 3]);
                let rest_q = Quat::from_euler(EulerRot::XYZ, rot[0].to_radians(), rot[1].to_radians(), rot[2].to_radians());
                let scale = match p.scale {
                    Some(Scale::Uniform(s)) => Vec3::splat(s),
                    Some(Scale::Xyz([x, y, z])) => Vec3::new(x, y, z),
                    None => Vec3::ONE,
                };
                Instance { matrix: Mat4::from_scale_rotation_translation(scale, rest_q, at), color: Color::WHITE }
            })
            .collect();
        let obj = Obj::instanced(&geo, &mat, instances);
        obj.get().lod = self.lod_of(first);
        obj.get().fade = self.fade;
        if !first.outline.unwrap_or(!matches!(first.geo, Some(Geo::Plane { .. } | Geo::Ring { .. }))) {
            obj.no_outline();
        }
        for p in run {
            if let Some(id) = &p.id {
                self.parts.insert(id.clone(), obj.clone());
            }
        }
        if let Some(tag) = first.tag.as_deref().and_then(tag_of) {
            obj.set_dynamic(true); // its colour or blink changes every frame
            self.live.push(Live {
                obj: obj.clone(),
                mat: Some(mat),
                tag: Some(tag),
                glow: glow_of(first.mat.as_ref()),
                rest: Vec3::ZERO,
                rest_q: Quat::IDENTITY,
                spin_axis: Vec3::Y,
                spin_rps: 0.0,
                pulse: None,
                blink: None,
                slide: None,
                swing: None,
                angle: 0.0,
            });
        }
        obj
    }

    fn part(&mut self, p: &Part) -> Obj {
        let at = Vec3::from(p.at.unwrap_or([0.0; 3]));
        match &p.repeat {
            Some(rep) => {
                let n = repeat_count(&rep.count, &self.vals);
                let node = if plain_repeat(p) { self.instanced(p, rep, at, n) } else { self.copies(p, rep, at, n) };
                if let Some(id) = &p.id {
                    self.parts.insert(id.clone(), node.clone());
                }
                node
            }
            None => {
                let node = self.node(p, at);
                if let Some(id) = &p.id {
                    self.parts.insert(id.clone(), node.clone());
                }
                node
            }
        }
    }

    /// A repeat as one node per copy: the general case (children, animation, tags, labels, use).
    fn copies(&mut self, p: &Part, rep: &Repeat, at: Vec3, n: u32) -> Obj {
        let group = Obj::group();
        for i in 0..n {
            let copy = self.node(p, at + repeat_offset(rep, i));
            group.add(&copy);
        }
        group
    }

    /// A repeat of a plain geometry as one instanced mesh: one draw for every copy (300 SMD
    /// resistors are one call). Each copy carries the part's own rest pose and scale.
    fn instanced(&mut self, p: &Part, rep: &Repeat, at: Vec3, n: u32) -> Obj {
        let (Some(g), mat) = (&p.geo, self.material_for(p)) else { return Obj::group() };
        let geo = geometry_of(g);
        let rot = p.rot.unwrap_or([0.0; 3]);
        let rest_q = Quat::from_euler(EulerRot::XYZ, rot[0].to_radians(), rot[1].to_radians(), rot[2].to_radians());
        let scale = match p.scale {
            Some(Scale::Uniform(s)) => Vec3::splat(s),
            Some(Scale::Xyz([x, y, z])) => Vec3::new(x, y, z),
            None => Vec3::ONE,
        };
        let instances: Vec<Instance> = (0..n)
            .map(|i| Instance { matrix: Mat4::from_scale_rotation_translation(scale, rest_q, at + repeat_offset(rep, i)), color: Color::WHITE })
            .collect();
        let obj = Obj::instanced(&geo, &mat, instances);
        obj.get().lod = self.lod_of(p);
        obj.get().fade = self.fade;
        if !p.outline.unwrap_or(!matches!(p.geo, Some(Geo::Plane { .. } | Geo::Ring { .. }))) {
            obj.no_outline();
        }
        obj
    }

    /// The detail level a part is shown at: its own, else the one it inherits.
    fn lod_of(&self, p: &Part) -> u8 {
        p.detail.unwrap_or(self.lod)
    }

    /// The material of a part. Plain parts share one material per spec, so a board's copper, mask
    /// and metal are a handful of materials and their draws batch. A lit or animated part keeps its
    /// own: its colour changes, and no other part must change with it.
    fn material_for(&mut self, p: &Part) -> Mat {
        let lit = p.tag.is_some() || p.anim.is_some() || matches!(resolve(p.mat.as_ref()), Some(i) if i.emissive.is_some());
        let decal = matches!(p.geo, Some(Geo::Plane { .. } | Geo::Ring { .. }));
        if lit {
            return material(p.mat.as_ref(), decal);
        }
        let key = format!("{:?}|{decal}", p.mat);
        self.mats.entry(key).or_insert_with(|| material(p.mat.as_ref(), decal)).clone()
    }

    /// One copy of a part at `at`: its geometry, transform, outline, children, label, and its
    /// animation record when it has a tag or an animation.
    fn node(&mut self, p: &Part, at: Vec3) -> Obj {
        let flat_geo = matches!(p.geo, Some(Geo::Plane { .. } | Geo::Ring { .. }));
        let mat = p.geo.as_ref().map(|_| self.material_for(p));
        let obj = match (&p.geo, &mat) {
            (Some(g), Some(m)) => Obj::mesh(&geometry_of(g), m),
            _ => Obj::group(),
        };
        let rot = p.rot.unwrap_or([0.0; 3]);
        let rest_q = Quat::from_euler(EulerRot::XYZ, rot[0].to_radians(), rot[1].to_radians(), rot[2].to_radians());
        obj.set_position(at.x, at.y, at.z).set_quaternion(rest_q);
        match p.scale {
            Some(Scale::Uniform(s)) => {
                obj.set_scalar(s);
            }
            Some(Scale::Xyz([x, y, z])) => {
                obj.set_scale(x, y, z);
            }
            None => {}
        }
        if !p.outline.unwrap_or(!flat_geo) {
            obj.no_outline();
        }

        // The detail and the cutaway this part and its children inherit (restored on the way out).
        let (saved_lod, saved_fade, saved_dynamic) = (self.lod, self.fade, self.dynamic);
        self.dynamic |= p.tag.is_some() || p.anim.is_some() || p.cutaway;
        self.lod = self.lod_of(p);
        obj.get().lod = self.lod;
        if p.cutaway {
            let id = self.fades.len() as u32 + 1;
            self.fade = id;
            self.fades.push((id, obj.clone()));
            obj.set_dynamic(true); // its draws fade every frame
        }
        obj.get().fade = self.fade;

        if let Some(name) = &p.use_ {
            if self.depth < MAX_USE_DEPTH {
                if let Some(m) = model(name) {
                    self.depth += 1;
                    self.add_parts(&obj, &m.parts);
                    self.depth -= 1;
                }
            }
        }
        self.add_parts(&obj, &p.children);
        if let Some(label) = &p.label {
            obj.add(&label_node(label, top_of(p.geo.as_ref())));
        }

        let tag = p.tag.as_deref().and_then(tag_of);
        if tag.is_some() || p.anim.is_some() {
            let anim = p.anim.as_ref();
            let spin = anim.and_then(|a| a.spin.as_ref());
            let blink = anim.and_then(|a| a.blink).map(|b| (b.period.max(0.01), b.phase));
            let gpu = gpu_anim_of(
                tag,
                spin.map(|s| (axis_of(&s.axis), s.rps)),
                blink,
                glow_of(p.mat.as_ref()),
                anim.is_some_and(|a| a.pulse.is_some() || a.slide.is_some() || a.swing.is_some()),
            );
            // Its pose or colour changes every frame, unless the GPU animates it (scene::GPU_HW_ANIM).
            obj.set_dynamic(!(scene::GPU_HW_ANIM && gpu.is_some()));
            if let Some(a) = gpu {
                obj.set_anim(a);
            }
            self.live.push(Live {
                obj: obj.clone(),
                mat,
                tag,
                glow: glow_of(p.mat.as_ref()),
                rest: at,
                rest_q,
                spin_axis: spin.map(|s| axis_of(&s.axis)).unwrap_or(Vec3::Y),
                spin_rps: spin.map(|s| s.rps).unwrap_or(0.0),
                pulse: anim.and_then(|a| a.pulse).map(|pu| pu.period.max(0.01)),
                blink,
                slide: anim.and_then(|a| a.slide.as_ref()).map(|s| (Vec3::from(s.to), s.on == "enter")),
                swing: anim
                    .and_then(|a| a.swing.as_ref())
                    .map(|s| (axis_of(&s.axis), s.to.to_radians(), s.on == "enter")),
                angle: 0.0,
            });
        }
        (self.lod, self.fade, self.dynamic) = (saved_lod, saved_fade, saved_dynamic);
        obj
    }
}

/// A repeat that can be one instanced mesh: a plain geometry, with nothing per copy (no children,
/// part file, label, animation or tag).
fn plain_repeat(p: &Part) -> bool {
    p.geo.is_some() && p.children.is_empty() && p.use_.is_none() && p.label.is_none() && p.anim.is_none() && p.tag.is_none()
}

/// The box of a cutaway's meshes in the root's frame: `world` is the node's own world matrix.
fn span_of(node: &Obj, world: Mat4, lo: &mut Vec3, hi: &mut Vec3) {
    let (geo, children) = {
        let n = node.get();
        let geo = match &n.kind {
            Kind::Mesh { geo, .. } => Some(Arc::clone(geo)),
            _ => None,
        };
        (geo, n.children.clone())
    };
    if let Some(geo) = geo {
        for p in &geo.positions {
            let w = world.transform_point3(Vec3::from(*p));
            *lo = lo.min(w);
            *hi = hi.max(w);
        }
    }
    for child in &children {
        span_of(child, world * child.local_matrix(), lo, hi);
    }
}

/// Builds a model's scene. `params` override the model's own `params` (a missing param is 0).
/// Parts are toon-shaded with ink outlines unless `flat`; `repeat`, `when`, `use`, `children`,
/// `scale`, `rot` and `label` are applied as the schema says. Only the parts that move (animated,
/// tagged, cutaway) are dynamic: the rest is baked by the scene.
pub fn build(model: &Model, params: &Params) -> Built {
    build_tinted(model, params, &[])
}

/// [`build`] with each shown GPU card's shroud tinted (the web's `retint`, `machine-stage.ts`): `tints[i]` is the tint of
/// the i-th card in card order, None keeps the palette's shroud. Without a tint the model builds exactly as `build`.
pub fn build_tinted(model: &Model, params: &Params, tints: &[Option<u32>]) -> Built {
    let tinted;
    let model = if tints.iter().any(Option::is_some) {
        tinted = tint_cards(model, tints);
        &tinted
    } else {
        model
    };
    let mut vals = model.params.clone();
    vals.extend(params.values.iter().map(|(k, v)| (k.clone(), *v)));
    let mut b = Builder { vals, parts: HashMap::new(), live: Vec::new(), depth: 0, mats: HashMap::new(), fades: Vec::new(), lod: 0, fade: 0, dynamic: false };
    let root = Obj::group();
    b.add_parts(&root, &model.parts);
    outline(&root, OUTLINE_MIN);
    let fades = b
        .fades
        .iter()
        .map(|(id, node)| {
            let world = root.world_matrix_of(node).unwrap_or(Mat4::IDENTITY);
            let (mut lo, mut hi) = (Vec3::splat(f32::MAX), Vec3::splat(f32::MIN));
            span_of(node, world, &mut lo, &mut hi);
            if lo.x > hi.x {
                lo = Vec3::ZERO;
                hi = Vec3::ZERO;
            }
            scene::Fade { id: *id, min: lo, max: hi }
        })
        .collect();
    let fade_nodes = b.fades.iter().map(|(_, node)| node.clone()).collect();
    Built { root, parts: b.parts, fades, fade_nodes, live: b.live, t: 0.0 }
}

/// The model with its GPU cards retinted: card i (the i-th top-level card part, in model order) takes an inline material of
/// `tints[i]` when it has one.
fn tint_cards(model: &Model, tints: &[Option<u32>]) -> Model {
    let mut out = model.clone();
    let cards: Vec<usize> = out.parts.iter().enumerate().filter(|(_, p)| is_card(p)).map(|(i, _)| i).collect();
    for (&card, tint) in cards.iter().zip(tints) {
        if let Some(t) = tint {
            let spec = MatSpec::Inline(InlineMat { color: Some(format!("#{t:06x}")), emissive: None, glow: 0.0, opacity: 1.0, additive: false, flat: false });
            retint(&mut out.parts[card], &spec, true);
        }
    }
    out
}

/// A top-level part gated by a `gpus` `when` that has a shroud, or is the laptop's bare chip (`ic`).
fn is_card(p: &Part) -> bool {
    p.when.as_deref().is_some_and(mentions_gpus) && (has_shroud(p) || is_mat(p.mat.as_ref(), "ic"))
}

/// Whether a `when` expression names the `gpus` param as a whole word (the web's `/\\bgpus\\b/`).
fn mentions_gpus(when: &str) -> bool {
    let word = |c: char| c.is_ascii_alphanumeric() || c == '_';
    when.match_indices("gpus").any(|(i, _)| {
        !when[..i].chars().next_back().is_some_and(word) && !when[i + 4..].chars().next().is_some_and(word)
    })
}

fn has_shroud(p: &Part) -> bool {
    is_mat(p.mat.as_ref(), "gpu-shroud") || p.children.iter().any(has_shroud)
}

fn is_mat(spec: Option<&MatSpec>, name: &str) -> bool {
    matches!(spec, Some(MatSpec::Name(n)) if n == name)
}

/// Points a card's shroud (and, on the top part, a bare chip) at `spec` (the web's `retint`).
fn retint(p: &mut Part, spec: &MatSpec, top: bool) {
    if is_mat(p.mat.as_ref(), "gpu-shroud") || (top && is_mat(p.mat.as_ref(), "ic")) {
        p.mat = Some(spec.clone());
    }
    for c in &mut p.children {
        retint(c, spec, false);
    }
}

/// A repeat's copy count, read from `vals` (see `Count`), at most 256 (the web's `repeatCount`). A named count reads its
/// param now; a missing or negative one repeats nothing. "p/n" is the param over n, rounded up.
fn repeat_count(count: &Count, vals: &BTreeMap<String, f64>) -> u32 {
    match count {
        Count::Num(n) => *n,
        Count::Param(s) => split_count(s)
            .and_then(|(name, div)| vals.get(name).map(|v| (v.round().max(0.0) as u32).div_ceil(div)))
            .unwrap_or(0),
    }
    .min(256)
}

/// A solid part's world box, one per copy (the web's `PartBox`, zfight.ts `partBoxes`). `id` is the part's id, or its
/// `path` when it has none; `path` is `parts[i]`, with `.children` and a `use` model's parts nested under it.
#[derive(Debug, Clone, PartialEq)]
pub struct PartBox {
    pub id: String,
    pub path: String,
    pub lo: [f32; 3],
    pub hi: [f32; 3],
}

/// The world boxes of a model's solid parts (the web's `partBoxes`): the same `when`, `repeat`, `use`, `children` and
/// transforms as `build`, each geometry's local bounds moved by its transform. Decals and empty outlines have none.
/// `params` are merged over the model's own, as `build` merges them.
pub fn part_boxes(model: &Model, params: &Params) -> Vec<PartBox> {
    let mut vals = model.params.clone();
    vals.extend(params.values.iter().map(|(k, v)| (k.clone(), *v)));
    let mut out = Vec::new();
    box_walk(&mut out, &vals, &model.parts, Mat4::IDENTITY, "parts", 0);
    out
}

fn box_walk(out: &mut Vec<PartBox>, vals: &BTreeMap<String, f64>, parts: &[Part], parent: Mat4, prefix: &str, depth: u32) {
    for (i, p) in parts.iter().enumerate() {
        // A `when` that fails, or does not parse, hides the part and its children (as the web's walk does).
        if p.when.as_deref().is_some_and(|expr| !parse_when(expr).is_ok_and(|w| eval_when(&w, vals))) {
            continue;
        }
        let path = format!("{prefix}[{i}]");
        let id = p.id.clone().unwrap_or_else(|| path.clone());
        let at = Vec3::from(p.at.unwrap_or([0.0; 3]));
        let offsets: Vec<Vec3> = match &p.repeat {
            Some(rep) => (0..repeat_count(&rep.count, vals)).map(|k| repeat_offset(rep, k)).collect(),
            None => vec![Vec3::ZERO],
        };
        // The part's own transform, as the web's localXf: Euler XYZ in degrees, then scale, then `at`.
        let [rx, ry, rz] = p.rot.unwrap_or([0.0; 3]).map(f32::to_radians);
        let turn = Mat4::from_rotation_x(rx) * Mat4::from_rotation_y(ry) * Mat4::from_rotation_z(rz);
        let scale = match p.scale {
            Some(Scale::Uniform(s)) => Vec3::splat(s),
            Some(Scale::Xyz(s)) => Vec3::from(s),
            None => Vec3::ONE,
        };
        for o in offsets {
            let m = parent * Mat4::from_translation(at + o) * turn * Mat4::from_scale(scale);
            if let Some((lo, hi)) = p.geo.as_ref().and_then(geo_bounds) {
                let (lo, hi) = world_box(m, lo, hi);
                out.push(PartBox { id: id.clone(), path: path.clone(), lo: lo.to_array(), hi: hi.to_array() });
            }
            if let Some(name) = &p.use_ {
                if let Some(used) = model(name).filter(|_| depth < MAX_USE_DEPTH) {
                    box_walk(out, vals, &used.parts, m, "parts", depth + 1);
                }
            }
            box_walk(out, vals, &p.children, m, &format!("{path}.children"), depth);
        }
    }
}

/// A geometry's bounds in its own frame (the web's `geoBounds`): None for decals (plane, ring) and an empty outline.
fn geo_bounds(g: &Geo) -> Option<(Vec3, Vec3)> {
    let half = |hx: f32, hy: f32, hz: f32| (Vec3::new(-hx, -hy, -hz), Vec3::new(hx, hy, hz));
    match g {
        Geo::Box { w, h, d } | Geo::Rbox { w, h, d, .. } => Some(half(w / 2.0, h / 2.0, d / 2.0)),
        Geo::Cyl { rt, rb, h, .. } => {
            let r = rt.max(*rb);
            Some(half(r, h / 2.0, r))
        }
        Geo::Cone { r, h } => Some(half(*r, h / 2.0, *r)),
        Geo::Sphere { r } => Some(half(*r, *r, *r)),
        Geo::Torus { r, tube, .. } => {
            let big = r + tube;
            Some(half(big, *tube, big))
        }
        Geo::Shape { points, h } => {
            if points.is_empty() {
                return None;
            }
            let lo_x = points.iter().map(|p| p[0]).fold(f32::INFINITY, f32::min);
            let hi_x = points.iter().map(|p| p[0]).fold(f32::NEG_INFINITY, f32::max);
            let lo_z = points.iter().map(|p| p[1]).fold(f32::INFINITY, f32::min);
            let hi_z = points.iter().map(|p| p[1]).fold(f32::NEG_INFINITY, f32::max);
            Some((Vec3::new(lo_x, 0.0, lo_z), Vec3::new(hi_x, *h, hi_z)))
        }
        Geo::Plane { .. } | Geo::Ring { .. } => None,
    }
}

/// The axis-aligned box of a local box after `m`: the min and max of its eight transformed corners (the web's `worldBox`).
fn world_box(m: Mat4, lo: Vec3, hi: Vec3) -> (Vec3, Vec3) {
    (0usize..8)
        .map(|k| {
            let pick = |bit: usize, a: f32, b: f32| if k & bit == 0 { a } else { b };
            m.transform_point3(Vec3::new(pick(1, lo.x, hi.x), pick(2, lo.y, hi.y), pick(4, lo.z, hi.z)))
        })
        .fold((Vec3::splat(f32::INFINITY), Vec3::splat(f32::NEG_INFINITY)), |(a, b), p| (a.min(p), b.max(p)))
}

impl Built {
    /// Takes the cutaways out of the per-frame walk, for a view that never fades them (the Machines
    /// view): their draws bake with the statics.
    pub fn freeze_cutaways(&mut self) {
        for node in &self.fade_nodes {
            node.set_dynamic(false);
        }
    }

    /// The live nodes this model animates or tags: each one is a draw the CPU moves every frame.
    pub fn animated_parts(&self) -> usize {
        self.live.len()
    }

    /// Advances the tags and animations by `dt` seconds.
    ///
    /// Tags: `status` LEDs take the status colour; `activity` LEDs blink while the machine is busy
    /// (`activity > 0`); `fan` spins when online, faster with `activity`; `screen` glows with
    /// activity. Anims: `spin`, `pulse`, `blink`, and `slide` / `swing` follow `open`.
    pub fn update(&mut self, dt: f32, clock: f32, state: &State) {
        // `dt` is the ambient step (the fans integrate it); `clock` is the ambient clock in seconds (the pulses and blinks read it).
        self.t = clock;
        let t = clock;
        let open = state.open.clamp(0.0, 1.0);
        let activity = state.activity.clamp(0.0, 1.0);
        let online = state.status == Status::Online;
        let busy = activity > 0.0;
        let led_ok = named("led-ok", 0x4fa36a);
        let led_off = named("led-off", 0x4a4f5c);

        for l in self.live.iter_mut() {
            if let Some((to, on_enter)) = l.slide {
                let k = if on_enter { open } else { 0.0 };
                let p = l.rest.lerp(to, k);
                l.obj.set_position(p.x, p.y, p.z);
            }
            let mut q = l.rest_q;
            if let Some((axis, to, on_enter)) = l.swing {
                let k = if on_enter { open } else { 0.0 };
                q *= Quat::from_axis_angle(axis, to * k);
            }
            let rps = match l.tag {
                Some(Tag::Fan) if online => 2.0 * (1.0 + 2.0 * activity),
                Some(Tag::Fan) => 0.0,
                _ => l.spin_rps,
            };
            if rps != 0.0 {
                l.angle = spin_step(l.angle, rps, dt);
                q *= Quat::from_axis_angle(l.spin_axis, l.angle);
            }
            l.obj.set_quaternion(q);

            let Some(mat) = &l.mat else { continue };
            let mut m = mat.get();
            if let Some(period) = l.pulse {
                m.emissive_intensity = l.glow.max(0.6) * (0.5 + 0.5 * (TAU * t / period).sin());
            }
            if let Some((period, phase)) = l.blink {
                m.emissive_intensity = blink_level(period, phase, l.glow, t);
            }
            match l.tag {
                Some(Tag::Status) => {
                    let c = status_color(state.status);
                    m.color = c;
                    m.emissive = c;
                    m.emissive_intensity = if l.glow > 0.0 { l.glow } else { 1.0 };
                }
                Some(Tag::Activity) => {
                    let on = busy && (t % 0.8) < 0.4;
                    let c = if on { led_ok } else { led_off };
                    m.color = c;
                    m.emissive = c;
                    m.emissive_intensity = if on { 1.5 } else { 0.1 };
                }
                Some(Tag::Screen) => m.emissive_intensity = l.glow * (0.5 + 0.5 * activity),
                _ => {}
            }
        }
    }
}

// ---- Traces and pulses ----------------------------------------------------------------------

/// The copper of every trace: one merged mesh of a thin strip per segment, lying at the trace's
/// `y`. Joints overlap by half a width at each end.
pub fn traces(model: &Model) -> Obj {
    let group = Obj::group();
    let mut pieces: Vec<(scene::Geo, Mat4)> = Vec::new();
    for tr in &model.traces {
        for w in tr.path.windows(2) {
            let (a, b) = (w[0], w[1]);
            let (dx, dz) = (b[0] - a[0], b[1] - a[1]);
            let len = (dx * dx + dz * dz).sqrt();
            if len <= 1e-6 {
                continue;
            }
            let mid = Vec3::new((a[0] + b[0]) * 0.5, tr.y, (a[1] + b[1]) * 0.5);
            let rot = Mat4::from_rotation_y((-dz).atan2(dx));
            let strip = geometry::box_geo(len + tr.width, 0.04, tr.width);
            pieces.push((strip, Mat4::from_translation(mid) * rot));
        }
    }
    if pieces.is_empty() {
        return group;
    }
    let copper = Mat::new(Material { color: named("copper", 0xb87333), ..Material::default() });
    group.add(&Obj::mesh(&scene::merge(&pieces), &copper));
    group
}

fn path_len(path: &[[f32; 2]]) -> f32 {
    path.windows(2).map(|w| ((w[1][0] - w[0][0]).powi(2) + (w[1][1] - w[0][1]).powi(2)).sqrt()).sum()
}

/// The point `d` units along a polyline (clamped to its end).
fn point_at(path: &[[f32; 2]], mut d: f32) -> [f32; 2] {
    for w in path.windows(2) {
        let (a, b) = (w[0], w[1]);
        let l = ((b[0] - a[0]).powi(2) + (b[1] - a[1]).powi(2)).sqrt();
        if d <= l {
            let t = if l > 0.0 { d / l } else { 0.0 };
            return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
        }
        d -= l;
    }
    path.last().copied().unwrap_or([0.0, 0.0])
}

struct Run {
    path: Vec<[f32; 2]>,
    y: f32,
    len: f32,
    phase: f32,
    speed: f32,
    /// Index among this trace's pulses, and how many it has: pulses light up with activity.
    k: usize,
    n: usize,
    sphere: Obj,
}

/// Current pulses: small additive spheres running along the traces. More of them are visible as
/// the machine gets busier (`update`'s `activity`).
pub struct Pulses {
    /// The group holding the spheres; add it to the scene.
    pub obj: Obj,
    runs: Vec<Run>,
}

impl Pulses {
    pub fn new(model: &Model) -> Pulses {
        let obj = Obj::group();
        obj.set_dynamic(true);
        let mat = Mat::new(Material {
            shading: Shading::Basic,
            color: Color::hex(0x7fe8ff),
            transparent: true,
            opacity: 0.9,
            additive: true,
            depth_write: false,
            ..Material::default()
        });
        let geo = geometry::sphere(0.14, 8, 6);
        let mut runs = Vec::new();
        for (i, tr) in model.traces.iter().enumerate() {
            let len = path_len(&tr.path);
            if len <= 0.0 {
                continue;
            }
            let n = ((len / 8.0).ceil() as usize).clamp(1, 4);
            for k in 0..n {
                let sphere = Obj::mesh(&geo, &mat);
                sphere.set_dynamic(true); // moved and shown every frame
                obj.add(&sphere);
                runs.push(Run {
                    path: tr.path.clone(),
                    y: tr.y,
                    len,
                    phase: k as f32 / n as f32,
                    speed: 4.0 + (i % 3) as f32,
                    k,
                    n,
                    sphere,
                });
            }
        }
        Pulses { obj, runs }
    }

    /// Moves the pulses by `dt` seconds; `activity` (0..1) sets how many show.
    pub fn update(&mut self, dt: f32, activity: f32) {
        let a = activity.clamp(0.0, 1.0);
        for r in self.runs.iter_mut() {
            r.phase = (r.phase + r.speed * dt / r.len).fract();
            let [x, z] = point_at(&r.path, r.phase * r.len);
            r.sphere.set_position(x, r.y, z);
            r.sphere.set_visible((r.k as f32) < a * r.n as f32);
        }
    }
}

// ---- The atom -------------------------------------------------------------------------------

/// The rest height of the atom inside `props::build_plaza` (its globe's y).
const ATOM_REST_Y: f32 = 4.2;

/// Places the plaza's atom at `anchors.atom` under `root`: scale 0.15 on an exterior, 1.0 on a
/// board. The atom is the same one the plaza draws (`props::atom`). Returns its animation, which the
/// caller must call every frame with the elapsed time. `None` when the model has no atom anchor, or
/// is a part.
pub fn place_atom(model: &Model, root: &Obj, palette: &PropPalette) -> Option<props::Anim> {
    let at = model.anchors.atom?;
    let scale = match model.view {
        View::Exterior => 0.15,
        View::Board => 1.0,
        View::Part => return None,
    };
    let (globe, anim) = props::atom(palette);
    let wrap = Obj::group();
    wrap.set_scalar(scale).set_position(at[0], at[1] - ATOM_REST_Y * scale, at[2]);
    wrap.set_dynamic(true); // the atom turns every frame
    wrap.add(&globe);
    // The same outline rule as the models: no ink on the specks of the atom.
    wrap.traverse(&mut |o: &Obj| {
        let tiny = match &o.get().kind {
            Kind::Mesh { geo, .. } | Kind::Instanced { geo, .. } => geo.radius < OUTLINE_MIN,
            _ => false,
        };
        if tiny {
            o.get().hull = None;
            o.no_outline();
        }
    });
    root.add(&wrap);
    Some(anim)
}

