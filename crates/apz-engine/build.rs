//! The engine's asset lists, built at compile time: the machine model kit (`assets/hardware/kit`) is listed into
//! `OUT_DIR/kit_files.rs`, and every `assets/robots/**/*.json` into `OUT_DIR/robot_files.rs`, so a new model or robot
//! file needs no Rust edit.
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR");
    println!("cargo:rerun-if-changed=build.rs");
    kit_files(Path::new(&manifest_dir));
    robot_files(Path::new(&manifest_dir));
}

/// Lists every JSON file under `assets/robots/` (species, tools, props, clips, palette, index) into
/// `OUT_DIR/robot_files.rs` as `("species/rover", include_str!(..))`. The key is the path under
/// `assets/robots/` without `.json`, with `/` separators. A new species file needs no Rust edit.
fn robot_files(manifest_dir: &Path) {
    let root = manifest_dir.join("../../assets/robots");
    let mut files: Vec<(String, PathBuf)> = Vec::new();
    collect_json(&root, &root, &mut files);
    files.sort();
    let mut list = String::new();
    for (key, file) in &files {
        let abs = fs::canonicalize(file).expect("robot file exists");
        list.push_str(&format!(
            "    ({:?}, include_str!({:?})),\n",
            key,
            abs.display().to_string()
        ));
    }
    let source = format!(
        "// Generated by build.rs from assets/robots: do not edit.\npub static ROBOT_FILES: &[(&str, &str)] = &[\n{list}];\n"
    );
    let out =
        PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("robot_files.rs");
    fs::write(&out, source).expect("write the robot file list");
}

/// Walks `dir` (under `root`): every `.json` file as (its path under `root` without `.json`, the file),
/// and every directory is watched so that a file added to it triggers a rebuild.
fn collect_json(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    println!("cargo:rerun-if-changed={}", dir.display());
    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(e) => panic!("robot assets: cannot read {}: {e}", dir.display()),
    };
    let mut paths: Vec<PathBuf> = entries.filter_map(|e| e.ok().map(|e| e.path())).collect();
    paths.sort();
    for path in paths {
        if path.is_dir() {
            collect_json(root, &path, out);
        } else if path.extension().is_some_and(|x| x == "json") {
            println!("cargo:rerun-if-changed={}", path.display());
            let rel = path
                .strip_prefix(root)
                .expect("under the robot root")
                .with_extension("");
            let key = rel
                .components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect::<Vec<_>>()
                .join("/");
            out.push((key, path));
        }
    }
}

/// Lists the machine model kit (`assets/hardware/kit`: the `.glb` models and the `.ktx2` textures) into
/// `OUT_DIR/kit_files.rs` as `("hub.glb", include_bytes!(..))`, sorted by name.
fn kit_files(manifest_dir: &Path) {
    let dir = manifest_dir.join("../../assets/hardware/kit");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut entries: Vec<(String, PathBuf)> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("kit assets: cannot read {}: {e}", dir.display()))
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| matches!(p.extension().and_then(|e| e.to_str()), Some("glb" | "ktx2")))
        .map(|p| (p.file_name().unwrap().to_string_lossy().into_owned(), p))
        .collect();
    entries.sort();
    let mut list = String::new();
    for (name, path) in &entries {
        println!("cargo:rerun-if-changed={}", path.display());
        let abs = path.canonicalize().expect("a kit file has a path");
        list.push_str(&format!(
            "    ({name:?}, include_bytes!({:?})),\n",
            abs.display().to_string()
        ));
    }
    let source = format!(
        "// Generated by build.rs from assets/hardware/kit: do not edit.\npub static KIT_FILES: &[(&str, &[u8])] = &[\n{list}];\n"
    );
    let out =
        PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("kit_files.rs");
    fs::write(&out, source).expect("write the kit file list");
}
