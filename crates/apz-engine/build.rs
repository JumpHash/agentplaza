//! The engine's asset lists, built at compile time: every `assets/hardware/{exterior,board,parts}/*.json`
//! is listed into `OUT_DIR/hardware_models.rs`, and every `assets/robots/**/*.json` into
//! `OUT_DIR/robot_files.rs`, so a new model or robot file needs no Rust edit. (Moved here from
//! `apps/desktop/build.rs` with the renderer.)
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR");
    println!("cargo:rerun-if-changed=build.rs");
    hardware_models(Path::new(&manifest_dir));
    robot_files(Path::new(&manifest_dir));
}

/// Lists every JSON file under `assets/robots/` (species, tools, props, clips, palette, index) into
/// `OUT_DIR/robot_files.rs` as `("species/rover", include_str!(..))`. The key is the path under
/// `assets/robots/` without `.json`, with `/` separators. A new species file needs no Rust edit.
fn robot_files(manifest_dir: &Path) {
    let root = manifest_dir.join("../../assets/robots");
    let mut files: Vec<(String, PathBuf)> = Vec::new();
    collect_json(&root, &root, &mut files);
    files.sort();
    let mut list = String::new();
    for (key, file) in &files {
        let abs = fs::canonicalize(file).expect("robot file exists");
        list.push_str(&format!(
            "    ({:?}, include_str!({:?})),\n",
            key,
            abs.display().to_string()
        ));
    }
    let source = format!(
        "// Generated by build.rs from assets/robots: do not edit.\npub static ROBOT_FILES: &[(&str, &str)] = &[\n{list}];\n"
    );
    let out =
        PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("robot_files.rs");
    fs::write(&out, source).expect("write the robot file list");
}

/// Walks `dir` (under `root`): every `.json` file as (its path under `root` without `.json`, the file),
/// and every directory is watched so that a file added to it triggers a rebuild.
fn collect_json(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    println!("cargo:rerun-if-changed={}", dir.display());
    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(e) => panic!("robot assets: cannot read {}: {e}", dir.display()),
    };
    let mut paths: Vec<PathBuf> = entries.filter_map(|e| e.ok().map(|e| e.path())).collect();
    paths.sort();
    for path in paths {
        if path.is_dir() {
            collect_json(root, &path, out);
        } else if path.extension().is_some_and(|x| x == "json") {
            println!("cargo:rerun-if-changed={}", path.display());
            let rel = path
                .strip_prefix(root)
                .expect("under the robot root")
                .with_extension("");
            let key = rel
                .components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect::<Vec<_>>()
                .join("/");
            out.push((key, path));
        }
    }
}

/// Lists the hardware model files: `exterior/*`, `board/*` and `workstation/*` (the workstations' exteriors, one per
/// OS family and form) as models, `parts/*` as part files. The keys are the file names with their folder
/// (`parts/gpu-pcie`, `workstation/mac-mini`).
fn hardware_models(manifest_dir: &Path) {
    let assets = manifest_dir.join("../../assets/hardware");
    println!("cargo:rerun-if-changed={}", assets.display());
    let mut models = String::new();
    let mut parts = String::new();
    for folder in ["exterior", "board", "parts", "workstation"] {
        let dir = assets.join(folder);
        println!("cargo:rerun-if-changed={}", dir.display());
        let mut files: Vec<PathBuf> = match fs::read_dir(&dir) {
            Ok(entries) => entries.filter_map(|e| e.ok().map(|e| e.path())).collect(),
            Err(e) => panic!("hardware assets: cannot read {}: {e}", dir.display()),
        };
        files.sort();
        for file in files
            .into_iter()
            .filter(|p| p.extension().is_some_and(|x| x == "json"))
        {
            println!("cargo:rerun-if-changed={}", file.display());
            let stem = file
                .file_stem()
                .and_then(|s| s.to_str())
                .expect("model file names are UTF-8");
            let abs = fs::canonicalize(&file).expect("model file exists");
            let line = format!(
                "    ({:?}, include_str!({:?})),\n",
                format!("{folder}/{stem}"),
                abs.display().to_string()
            );
            if folder == "parts" {
                parts.push_str(&line);
            } else {
                models.push_str(&line);
            }
        }
    }
    let source = format!(
        "// Generated by build.rs from assets/hardware: do not edit.\npub static MODELS: &[(&str, &str)] = &[\n{models}];\npub static PARTS: &[(&str, &str)] = &[\n{parts}];\n"
    );
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR"))
        .join("hardware_models.rs");
    fs::write(&out, source).expect("write the hardware model list");
}
