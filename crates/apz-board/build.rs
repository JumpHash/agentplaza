// Embeds the hardware assets (assets/hardware/board, parts and palette.json) as a table of
// (name, source text) in OUT_DIR/embedded.rs. A new file in those folders is picked up on the next build.
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn json_files(dir: &Path) -> Vec<PathBuf> {
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut out: Vec<PathBuf> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("apz-board build: cannot read {}: {e}", dir.display()))
        .map(|entry| entry.expect("apz-board build: directory entry").path())
        .filter(|p| p.extension().is_some_and(|e| e == "json"))
        .collect();
    out.sort();
    for p in &out {
        println!("cargo:rerun-if-changed={}", p.display());
    }
    out
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let hardware = fs::canonicalize(manifest.join("../../assets/hardware"))
        .expect("apz-board build: assets/hardware not found");
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    for p in json_files(&hardware.join("board")) {
        let stem = p
            .file_stem()
            .and_then(|s| s.to_str())
            .expect("file stem")
            .to_string();
        entries.push((format!("board/{stem}"), p));
    }
    for p in json_files(&hardware.join("parts")) {
        let stem = p
            .file_stem()
            .and_then(|s| s.to_str())
            .expect("file stem")
            .to_string();
        entries.push((format!("parts/{stem}"), p));
    }
    let palette = hardware.join("palette.json");
    println!("cargo:rerun-if-changed={}", palette.display());
    entries.push(("palette".to_string(), palette));

    let mut src = String::from(
        "/// (name, source) for every embedded hardware file. Generated by build.rs.\npub static EMBEDDED: &[(&str, &str)] = &[\n",
    );
    for (name, path) in &entries {
        src.push_str(&format!(
            "    ({name:?}, include_str!({:?})),\n",
            path.display().to_string()
        ));
    }
    src.push_str("];\n");
    fs::write(out_dir.join("embedded.rs"), src).expect("apz-board build: write embedded.rs");
}
