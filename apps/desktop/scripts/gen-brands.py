#!/usr/bin/env python3
"""Writes apps/desktop/src/console/brands.rs from apps/web/src/ui/brands.gen.ts (simple-icons,
CC0): the providers' marks, the same set the web console's model picker uses."""
import json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parents[3]
src = (ROOT / "apps/web/src/ui/brands.gen.ts").read_text()
body = src[src.index("{", src.index("BRAND_ICONS")) : src.rindex("}") + 1]
icons = json.loads(re.sub(r",\s*}", "}", body))
out = ["//! Provider and service marks (simple-icons, CC0), generated by `scripts/gen-brands.py` from",
       "//! `apps/web/src/ui/brands.gen.ts` — the same marks the web console shows. Do not edit.", "",
       "/// A mark: its title, brand colour (0xRRGGBB) and a 24×24 SVG document. A single-colour mark is",
       "/// filled in that colour (marks that are black or nearly are filled in the console's ink); a",
       "/// multi-colour mark keeps each path's own fill, never tinted.",
       "pub struct Brand {", "    pub title: &'static str,", "    pub hex: u32,", "    pub svg: &'static str,", "}", "",
       "/// The mark for `key` (\"anthropic\", \"openai\", \"deepseek\", …), or None.",
       "pub fn get(key: &str) -> Option<Brand> {", "    Some(match key {"]
for key, icon in icons.items():
    if "paths" in icon:  # multi-colour mark (e.g. huggingface): each path keeps its own fill
        paths = "".join(f'<path fill="{p["fill"]}" d="{p["d"]}"/>' for p in icon["paths"])
    else:
        hexv = int(icon["hex"], 16)
        r, g, b = (hexv >> 16) & 255, (hexv >> 8) & 255, hexv & 255
        fill = "#121613" if 0.2126 * r + 0.7152 * g + 0.0722 * b < 40 else "#" + icon["hex"]
        paths = f'<path fill="{fill}" d="{icon["path"]}"/>'
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">{paths}</svg>'
    title = icon["title"].replace('"', '\\"')
    out.append(f'        "{key}" => Brand {{ title: "{title}", hex: 0x{icon["hex"].upper()}, svg: r##"{svg}"## }},')
out += ["        _ => return None,", "    })", "}", ""]
(ROOT / "apps/desktop/src/console/brands.rs").write_text("\n".join(out))
print(len(icons), "marks")
