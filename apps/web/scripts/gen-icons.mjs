// Run: node scripts/gen-icons.mjs
import * as lucide from 'lucide';
import { writeFileSync } from 'node:fs';

const names = {
  overview: 'LayoutDashboard', agents: 'Bot', tasks: 'ListChecks', models: 'Cpu', conversations: 'MessagesSquare',
  board: 'Megaphone', council: 'Landmark', treasury: 'Coins', floor: 'Box', machine: 'Server', plus: 'Plus',
  send: 'SendHorizontal', stop: 'Square', x: 'X', check: 'Check', alert: 'TriangleAlert', play: 'Play',
  refresh: 'RefreshCw', key: 'KeyRound', trash: 'Trash2', edit: 'Pencil', chevronRight: 'ChevronRight',
  chevronDown: 'ChevronDown', terminal: 'Terminal', wrench: 'Wrench', brain: 'Brain', user: 'User',
  society: 'Share2', memory: 'Brain', heart: 'Heart', link: 'Link',
  orchestrator: 'Network', search: 'Search', external: 'ExternalLink', clock: 'Clock', zap: 'Zap',
  file: 'FileText', settings: 'SlidersHorizontal', ban: 'Ban', copy: 'Copy', sparkles: 'Sparkles', projects: 'FolderKanban', git: 'GitBranch', pull: 'GitPullRequest', commit: 'GitCommitHorizontal', loop: 'Repeat', harness: 'Gauge', rules: 'Scale',
};
const out = {};
for (const [key, name] of Object.entries(names)) {
  if (!lucide[name]) { console.error(`missing ${name}`); process.exit(1); }
  out[key] = lucide[name];
}
writeFileSync(new URL('../src/ui/icons.gen.ts', import.meta.url), `// Generated by scripts/gen-icons.mjs from lucide (ISC). Do not edit.
export type IconNode = [string, Record<string, string>][];
export const ICONS = ${JSON.stringify(out)} as const satisfies Record<string, IconNode>;
export type IconName = keyof typeof ICONS;
`);
console.log(`icons: ${Object.keys(out).length}`);
