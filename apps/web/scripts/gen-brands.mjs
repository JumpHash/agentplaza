// Regenerates src/ui/brands.gen.ts: the provider logos the console shows,
// taken from simple-icons (CC0; v11 for the brands later releases dropped). Brands it lacks get a monogram tile.
// Run: node scripts/gen-brands.mjs
import * as latest from 'simple-icons';
import * as v11 from 'simple-icons-11';
import { readFileSync, writeFileSync } from 'node:fs';

// Our brand key → simple-icons export name.
const map = {
  anthropic: 'siAnthropic', claude: 'siClaude', openai: 'siOpenai', google: 'siGooglegemini', aws: 'siAmazonaws',
  azure: 'siMicrosoftazure', microsoft: 'siMicrosoft', xai: 'siX', deepseek: 'siDeepseek', zai: 'siZdotai', moonshot: 'siMoonshotai', mistral: 'siMistralai',
  openrouter: 'siOpenrouter', opencode: 'siOpencode', perplexity: 'siPerplexity', nvidia: 'siNvidia', ollama: 'siOllama',
  lmstudio: 'siLmstudio', vllm: 'siVllm', huggingface: 'siHuggingface',
  // External-tool connectors (Firecrawl, Higgsfield and Magnific have no simple-icons entry: monograms).
  elevenlabs: 'siElevenlabs', unsplash: 'siUnsplash', pexels: 'siPexels', pixabay: 'siPixabay',
  replicate: 'siReplicate', telegram: 'siTelegram', cloudflare: 'siCloudflare', digitalocean: 'siDigitalocean',
  github: 'siGithub', namecheap: 'siNamecheap', meta: 'siMeta',
};
// Marks simple-icons lacks, drawn from the brand's own logo (traced to a 24×24 path).
const custom = {
  // TypeSafe AI (Jev): its isometric S, from typesafe.ai's mark; the brand pink.
  typesafe: { title: 'TypeSafe Jev', hex: 'E551BA', path: 'M11.92 0L16.49 2.88L16.49 6.97L20.25 9.46L20.25 18.67L12.04 24L7.51 21.08L7.51 16.83L3.75 14.34L3.75 5.29ZM11.16 2.36L5.35 6.17L5.39 12.46L7.51 11.06L7.51 7.05L11.2 4.57ZM12.84 2.36L12.8 4.57L14.92 5.97L14.96 3.77ZM11.96 5.97L9.76 7.45L12.04 8.93L14.24 7.45ZM9.08 8.93L9.04 11.06L11.16 12.46L11.2 10.34ZM14.84 8.93L12.8 10.34L12.8 14.34L9.04 16.83L9.08 19.19L14.96 15.31ZM16.53 8.93L16.49 15.31L18.61 16.71L18.65 10.34ZM8.27 12.46L5.99 13.94L8.19 15.43L10.56 13.94ZM15.73 16.71L9.76 20.67L12.12 22.08L17.09 18.87L18.01 18.19Z' },
};
const out = {};
for (const [key, name] of Object.entries(map)) {
  const icon = latest[name] ?? v11[name];
  if (!icon) { console.error(`missing ${name}`); process.exit(1); }
  out[key] = { title: icon.title, hex: icon.hex, path: icon.path };
}
Object.assign(out, custom);
// Meta's brand colour; simple-icons carries an older blue.
out.meta.hex = '0081FB';
// Multi-colour marks: each <path> keeps its own fill (never tinted). The SVG is the
// MIT-licensed LobeHub icon set, 24x24, <title> stripped. Replaces the single silhouette.
const multi = { huggingface: 'brands/huggingface.svg' };
for (const [key, file] of Object.entries(multi)) {
  const svg = readFileSync(new URL(file, import.meta.url), 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)" fill="([^"]+)"/g)].map(([, d, fill]) => ({ d, fill }));
  if (!paths.length) { console.error(`no paths in ${file}`); process.exit(1); }
  delete out[key].path;
  out[key].paths = paths;
}
const body = `// Generated by scripts/gen-brands.mjs from simple-icons (CC0) and brands/*.svg (MIT). Do not edit.
// \`path\` is a single-colour silhouette; \`paths\` is a multi-colour mark, drawn with each path's own fill.
export interface BrandPath { d: string; fill: string }
export interface BrandIcon { title: string; hex: string; path?: string; paths?: BrandPath[] }
export const BRAND_ICONS: Record<string, BrandIcon> = ${JSON.stringify(out, null, 1)};
`;
writeFileSync(new URL('../src/ui/brands.gen.ts', import.meta.url), body);
console.log(`brands: ${Object.keys(out).length} icons`);
