const body = `// Generated by scripts/gen-brands.mjs from simple-icons (CC0). Do not edit.
export interface BrandIcon { title: string; hex: string; path: string }
export const BRAND_ICONS: Record<string, BrandIcon> = ${JSON.stringify(out, null, 1)};
`;
writeFileSync(new URL('../src/ui/brands.gen.ts', import.meta.url), body);
console.log(`brands: ${Object.keys(out).length} icons`);
