#!/usr/bin/env python3
"""Regenerate docs/agents/initial-roles.json from the planning repo's role.yaml files.

Usage: python3 scripts/gen-roles.py <planning-repo>

Builds one manifest entry per planning role (PLANNING_ROLES), keeps the
orchestrator entry, drops every other role, and copies each role's prompt.md
into docs/codex-draft/roles/<role>/prompt.md. Every entry carries its slot:
the role's guest CID is the fleet's CID base plus its slot, so slots are never
renumbered (see slot_table).
"""
import json
import pathlib
import shutil
import sys

import yaml

PLANNING_ROLES = [
    "architect",
    "auditor",
    "breeder",
    "builder",
    "edge-operator",
    "finance",
    "incident",
    "librarian",
    "mayor",
    "mayor-office",
    "planner",
    "qa",
    "release",
    "researcher",
    "reviewer",
    "security-reviewer",
]
SOURCE = "generated by scripts/gen-roles.py from the planning repo role.yaml files, plus orchestrator"

# Each role's slot: its guest CID is the fleet's CID base plus the slot. These
# are the CIDs the sixteen roles had before `breeder` existed (alphabetical from
# the base), pinned so that adding a role never moves another role's CID.
PINNED_SLOTS = {
    "architect": 0,
    "auditor": 1,
    "builder": 2,
    "edge-operator": 3,
    "finance": 4,
    "incident": 5,
    "librarian": 6,
    "mayor": 7,
    "mayor-office": 8,
    "orchestrator": 9,
    "planner": 10,
    "qa": 11,
    "release": 12,
    "researcher": 13,
    "reviewer": 14,
    "security-reviewer": 15,
}

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "docs" / "agents" / "initial-roles.json"
PROMPTS = ROOT / "docs" / "codex-draft" / "roles"


def budget_of(src):
    budget = src.get("budget", 0)
    if isinstance(budget, dict):
        return budget.get("default_credits", 0)
    return budget


def slot_table(old_roles, names):
    """The slot of each of `names`, never renumbering one that has a slot.

    A pinned role keeps its pinned slot (a manifest that disagrees is refused),
    any other role keeps the slot the manifest gives it, and a role with no slot
    yet takes the next one after the highest slot ever used, so a retired slot
    is not reused either.
    """
    slots = dict(PINNED_SLOTS)
    for name, entry in old_roles.items():
        if "slot" not in entry:
            continue
        if name in PINNED_SLOTS and entry["slot"] != PINNED_SLOTS[name]:
            sys.exit(f"{name}: slot {entry['slot']} would renumber it (pinned at {PINNED_SLOTS[name]})")
        slots[name] = entry["slot"]
    next_slot = max(slots.values(), default=-1) + 1
    for name in names:
        if name not in slots:
            slots[name] = next_slot
            next_slot += 1
    return {name: slots[name] for name in names}


def with_slot(entry, slot):
    """The entry with its slot written straight after its role name."""
    rest = {key: value for key, value in entry.items() if key not in ("role", "slot")}
    return {"role": entry["role"], "slot": slot, **rest}


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    planning = pathlib.Path(sys.argv[1]) / "drafts" / "codex" / "roles"
    current = json.loads(MANIFEST.read_text())
    old_roles = current["roles"]
    slots = slot_table(old_roles, PLANNING_ROLES + ["orchestrator"])

    roles = {}
    for name in PLANNING_ROLES:
        src = yaml.safe_load((planning / name / "role.yaml").read_text())
        if src.get("role") != name:
            sys.exit(f"{name}: role.yaml declares role {src.get('role')!r}")
        old = old_roles.get(name, {})
        roles[name] = with_slot({
            "role": name,
            "title": old.get("title") or name.replace("-", " ").capitalize(),
            "permits": list(src.get("permits") or []),
            "toolsets": list(src.get("toolsets") or []),
            "budget": budget_of(src),
            "variant": src.get("variant") or None,
            "tools": list(src.get("tools") or []),
        }, slots[name])
        dest = PROMPTS / name
        dest.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(planning / name / "prompt.md", dest / "prompt.md")

    roles["orchestrator"] = with_slot(old_roles["orchestrator"], slots["orchestrator"])
    MANIFEST.write_text(json.dumps({"source": SOURCE, "roles": roles}, indent=1) + "\n")
    print(f"wrote {len(roles)} roles to {MANIFEST}")


if __name__ == "__main__":
    main()
